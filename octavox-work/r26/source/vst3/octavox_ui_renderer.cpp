UiRenderer::UiRenderer(uint32_t* pixels, int w, int h)
    : pixels_(pixels), w_(w), h_(h) {}

void UiRenderer::clear(uint32_t c) {
    if (!pixels_) return;
    const size_t n = static_cast<size_t>(w_) * static_cast<size_t>(h_);
    for (size_t i = 0; i < n; ++i) pixels_[i] = c;
}

void UiRenderer::rect(int x, int y, int w, int h, uint32_t c) {
    if (w <= 0 || h <= 0) return;
    const int x0 = x < 0 ? 0 : x;
    const int y0 = y < 0 ? 0 : y;
    const int x1 = x + w > w_ ? w_ : x + w;
    const int y1 = y + h > h_ ? h_ : y + h;
    for (int yy = y0; yy < y1; ++yy) {
        uint32_t* row = pixels_ + static_cast<size_t>(yy) * w_;
        for (int xx = x0; xx < x1; ++xx) row[xx] = c;
    }
}

void UiRenderer::frame(int x, int y, int w, int h, uint32_t c) {
    if (w <= 0 || h <= 0) return;
    hline(x, y, w, c);
    hline(x, y + h - 1, w, c);
    vline(x, y, h, c);
    vline(x + w - 1, y, h, c);
}

void UiRenderer::hline(int x, int y, int w, uint32_t c) {
    if (y < 0 || y >= h_) return;
    const int x0 = x < 0 ? 0 : x;
    const int x1 = x + w > w_ ? w_ : x + w;
    uint32_t* row = pixels_ + static_cast<size_t>(y) * w_;
    for (int xx = x0; xx < x1; ++xx) row[xx] = c;
}

void UiRenderer::vline(int x, int y, int h, uint32_t c) {
    if (x < 0 || x >= w_) return;
    const int y0 = y < 0 ? 0 : y;
    const int y1 = y + h > h_ ? h_ : y + h;
    for (int yy = y0; yy < y1; ++yy)
        pixels_[static_cast<size_t>(yy) * w_ + x] = c;
}

void UiRenderer::disc(int cx, int cy, int r, uint32_t c) {
    if (r < 0) return;
    for (int dy = -r; dy <= r; ++dy) {
        const int y = cy + dy;
        if (y < 0 || y >= h_) continue;
        const int s = static_cast<int>(
            std::sqrt(static_cast<double>(r * r - dy * dy)));
        const int x0 = cx - s, x1 = cx + s;
        uint32_t* row = pixels_ + static_cast<size_t>(y) * w_;
        for (int xx = x0 < 0 ? 0 : x0; xx <= x1 && xx < w_; ++xx) row[xx] = c;
    }
}

int UiRenderer::textWidth(const char* s, int scale) const {
    if (!s || !*s || scale < 1) return 0;
    int n = 0;
    for (const char* p = s; *p; ++p) ++n;
    return n * 6 * scale - scale;  // last spacing column omitted
}

void UiRenderer::text(int x, int y, const char* s, uint32_t c, int scale) {
    if (!s || scale < 1) return;
    int cx = x;
    for (const char* p = s; *p; ++p) {
        const unsigned char code = static_cast<unsigned char>(*p);
        if (code >= 32 && code <= 126) {
            for (int col = 0; col < 5; ++col) {
                const uint8_t bits = glyphColumn(code, col);
                const int px = cx + col * scale;
                for (int row = 0; row < 7; ++row) {
                    if (bits & (1u << row)) {
                        const int py = y + row * scale;
                        rect(px, py, scale, scale, c);
                    }
                }
            }
        }
        cx += 6 * scale;
    }
}

void UiRenderer::textRight(int xRight, int y, const char* s, uint32_t c,
                           int scale) {
    text(xRight - textWidth(s, scale), y, s, c, scale);
}

void UiRenderer::textCenter(int cx, int y, const char* s, uint32_t c,
                            int scale) {
    text(cx - textWidth(s, scale) / 2, y, s, c, scale);
}

